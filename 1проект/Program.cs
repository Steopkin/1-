using _1проект;

// Задача 2. Пользователь вводит N, программа выводит сумму 1 + 2 + … +N.
Console.Write("введите число == ");
int n = Convert.ToInt32(Console.ReadLine());

int sum = 0;
for (int s = 1; s <= n; s++)
{
    sum = sum + s;
}
Console.Write(sum + "-- сумма");

